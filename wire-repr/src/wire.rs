/// Invalid framing for a sequence of fixed-width wire views.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FixedViewSequenceError {
    /// The generated item representation has zero width.
    InvalidItemWidth,
    /// Input ends with an incomplete item.
    TrailingPartialItem {
        /// Complete item width.
        item_width: usize,
        /// Bytes left after the last complete item.
        trailing: usize,
    },
}

impl core::fmt::Display for FixedViewSequenceError {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::InvalidItemWidth => {
                formatter.write_str("fixed sequence items must consume bytes")
            }
            Self::TrailingPartialItem {
                item_width,
                trailing,
            } => write!(
                formatter,
                "fixed sequence has {trailing} trailing bytes, fewer than one {item_width}-byte item",
            ),
        }
    }
}

impl core::error::Error for FixedViewSequenceError {}

/// Failure while framing or semantically validating a fixed-width view sequence.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FixedValidatedViewSequenceError<E> {
    /// Sequence framing failed.
    Framing(FixedViewSequenceError),
    /// An item failed semantic validation.
    Item(E),
}

impl<E: core::fmt::Display> core::fmt::Display for FixedValidatedViewSequenceError<E> {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Framing(error) => error.fmt(formatter),
            Self::Item(error) => error.fmt(formatter),
        }
    }
}

impl<E: core::fmt::Debug + core::fmt::Display> core::error::Error
    for FixedValidatedViewSequenceError<E>
{
}

/// An infallible iterator over preframed fixed-width wire views.
#[derive(Clone, Debug)]
pub struct FixedViewIterator<'wire, V> {
    #[cfg(not(feature = "bytes"))]
    chunks: core::slice::ChunksExact<'wire, u8>,
    #[cfg(not(feature = "bytes"))]
    make_view: fn(&'wire [u8]) -> V,
    #[cfg(feature = "bytes")]
    remaining: bytes::Bytes,
    #[cfg(feature = "bytes")]
    item_width: usize,
    #[cfg(feature = "bytes")]
    make_view: fn(bytes::Bytes) -> V,
    #[cfg(feature = "bytes")]
    view: core::marker::PhantomData<&'wire ()>,
}

impl<'wire, V> FixedViewIterator<'wire, V> {
    /// Validates fixed-width sequence framing and creates its iterator.
    #[doc(hidden)]
    #[cfg(not(feature = "bytes"))]
    pub fn new(
        input: &'wire [u8],
        item_width: usize,
        make_view: fn(&'wire [u8]) -> V,
    ) -> Result<Self, FixedViewSequenceError> {
        if item_width == 0 {
            return Err(FixedViewSequenceError::InvalidItemWidth);
        }
        let chunks = input.chunks_exact(item_width);
        let trailing = chunks.remainder().len();
        if trailing != 0 {
            return Err(FixedViewSequenceError::TrailingPartialItem {
                item_width,
                trailing,
            });
        }
        Ok(Self { chunks, make_view })
    }

    /// Validates fixed-width sequence framing and creates its iterator from owned input.
    #[doc(hidden)]
    #[cfg(feature = "bytes")]
    pub fn new(
        input: bytes::Bytes,
        item_width: usize,
        make_view: fn(bytes::Bytes) -> V,
    ) -> Result<Self, FixedViewSequenceError> {
        if item_width == 0 {
            return Err(FixedViewSequenceError::InvalidItemWidth);
        }
        let trailing = input.len() % item_width;
        if trailing != 0 {
            return Err(FixedViewSequenceError::TrailingPartialItem {
                item_width,
                trailing,
            });
        }
        Ok(Self {
            remaining: input,
            item_width,
            make_view,
            view: core::marker::PhantomData,
        })
    }
}

impl<'wire, V> Iterator for FixedViewIterator<'wire, V> {
    type Item = V;

    fn next(&mut self) -> Option<Self::Item> {
        #[cfg(not(feature = "bytes"))]
        {
            self.chunks.next().map(self.make_view)
        }
        #[cfg(feature = "bytes")]
        {
            (!self.remaining.is_empty())
                .then(|| (self.make_view)(self.remaining.split_to(self.item_width)))
        }
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        #[cfg(not(feature = "bytes"))]
        {
            self.chunks.size_hint()
        }
        #[cfg(feature = "bytes")]
        {
            let len = self.remaining.len() / self.item_width;
            (len, Some(len))
        }
    }
}

impl<V> ExactSizeIterator for FixedViewIterator<'_, V> {
    fn len(&self) -> usize {
        #[cfg(not(feature = "bytes"))]
        {
            self.chunks.len()
        }
        #[cfg(feature = "bytes")]
        {
            self.remaining.len() / self.item_width
        }
    }
}

impl<V> core::iter::FusedIterator for FixedViewIterator<'_, V> {}

/// An infallible iterator over fixed-width views retaining an arbitrary backing.
#[doc(hidden)]
#[derive(Clone, Debug)]
pub struct GenericFixedViewIterator<B: ViewBacking, V> {
    remaining: Option<B>,
    item_width: usize,
    make_view: fn(B) -> V,
}

impl<B: ViewBacking, V> GenericFixedViewIterator<B, V> {
    /// Validates fixed-width sequence framing and creates its iterator.
    #[doc(hidden)]
    pub fn new(
        input: B,
        item_width: usize,
        make_view: fn(B) -> V,
    ) -> Result<Self, FixedViewSequenceError> {
        if item_width == 0 {
            return Err(FixedViewSequenceError::InvalidItemWidth);
        }
        let trailing = input.as_bytes().len() % item_width;
        if trailing != 0 {
            return Err(FixedViewSequenceError::TrailingPartialItem {
                item_width,
                trailing,
            });
        }
        Ok(Self {
            remaining: Some(input),
            item_width,
            make_view,
        })
    }
}

impl<B: ViewBacking, V> Iterator for GenericFixedViewIterator<B, V> {
    type Item = V;

    fn next(&mut self) -> Option<Self::Item> {
        let backing = self.remaining.take()?;
        let (item, remaining) = backing.split_at(self.item_width)?;
        self.remaining = Some(remaining);
        Some((self.make_view)(item))
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        let len = self
            .remaining
            .as_ref()
            .map_or(0, |backing| backing.as_bytes().len() / self.item_width);
        (len, Some(len))
    }
}

impl<B: ViewBacking, V> DoubleEndedIterator for GenericFixedViewIterator<B, V> {
    fn next_back(&mut self) -> Option<Self::Item> {
        let len = self.remaining.as_ref()?.as_bytes().len();
        if len == 0 {
            return None;
        }
        let backing = self.remaining.take()?;
        let (remaining, item) = backing.split_at(len - self.item_width)?;
        self.remaining = Some(remaining);
        Some((self.make_view)(item))
    }
}

impl<B: ViewBacking, V> ExactSizeIterator for GenericFixedViewIterator<B, V> {}

impl<B: ViewBacking, V> core::iter::FusedIterator for GenericFixedViewIterator<B, V> {}

/// Failure while advancing through a sequence of variable-width wire views.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ViewCursorError<E> {
    /// The next representation was structurally invalid.
    Item(E),
    /// A successful item consumed no bytes and therefore cannot advance a sequence.
    EmptyItem,
}

impl<E: core::fmt::Display> core::fmt::Display for ViewCursorError<E> {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Item(error) => error.fmt(formatter),
            Self::EmptyItem => formatter.write_str("a sequence item consumed no bytes"),
        }
    }
}

impl<E: core::fmt::Debug + core::fmt::Display> core::error::Error for ViewCursorError<E> {}

/// A fail-closed cursor over consecutive variable-width wire views.
#[cfg_attr(not(feature = "bytes"), derive(Copy))]
#[derive(Clone, Debug)]
pub struct ViewCursor<'wire, V> {
    #[cfg(not(feature = "bytes"))]
    remaining: &'wire [u8],
    #[cfg(feature = "bytes")]
    remaining: bytes::Bytes,
    view: core::marker::PhantomData<(&'wire (), V)>,
}

impl<'wire, V> ViewCursor<'wire, V> {
    /// Creates a cursor over `input` without validating an item yet.
    #[doc(hidden)]
    #[must_use]
    #[cfg(not(feature = "bytes"))]
    pub const fn new(input: &'wire [u8]) -> Self {
        Self {
            remaining: input,
            view: core::marker::PhantomData,
        }
    }

    /// Creates a cursor over owned input without validating an item yet.
    #[doc(hidden)]
    #[must_use]
    #[cfg(feature = "bytes")]
    pub fn new(input: bytes::Bytes) -> Self {
        Self {
            remaining: input,
            view: core::marker::PhantomData,
        }
    }

    /// Returns the unconsumed bytes.
    #[must_use]
    #[cfg(not(feature = "bytes"))]
    pub const fn remaining(&self) -> &'wire [u8] {
        self.remaining
    }

    /// Returns the unconsumed bytes.
    #[must_use]
    #[cfg(feature = "bytes")]
    pub fn remaining(&self) -> &[u8] {
        &self.remaining
    }
}

impl<'wire, V> ViewCursor<'wire, V>
where
    V: WireView<'wire>,
{
    /// Validates and returns the next item, or `None` at the exact end.
    ///
    /// An error leaves the cursor at the failing item.
    #[allow(clippy::should_implement_trait)]
    pub fn next(&mut self) -> Result<Option<V>, ViewCursorError<V::DecodeError>> {
        if self.remaining.is_empty() {
            return Ok(None);
        }
        #[cfg(not(feature = "bytes"))]
        let (view, suffix) = V::parse_view(self.remaining).map_err(ViewCursorError::Item)?;
        #[cfg(feature = "bytes")]
        let (view, suffix) =
            V::parse_view(self.remaining.clone()).map_err(ViewCursorError::Item)?;
        if suffix.len() == self.remaining.len() {
            return Err(ViewCursorError::EmptyItem);
        }
        self.remaining = suffix;
        Ok(Some(view))
    }
}

