/// Storage retained by a generated wire view.
///
/// Implementations must preserve the original bytes when splitting or slicing. Checked
/// operations return `None` for ranges outside the backing rather than panicking.
#[doc(hidden)]
pub trait ViewBacking: Sized + Clone {
    /// Consumes this backing and splits it into a prefix of `length` bytes and its suffix.
    #[must_use]
    fn split_at(self, length: usize) -> Option<(Self, Self)>;

    /// Returns a checked immutable slice of this backing.
    #[must_use]
    fn checked_slice(&self, range: core::ops::Range<usize>) -> Option<Self>;

    /// Returns the retained bytes without allocation.
    fn as_bytes(&self) -> &[u8];
}

impl ViewBacking for &[u8] {
    fn split_at(self, length: usize) -> Option<(Self, Self)> {
        self.get(..length).zip(self.get(length..))
    }

    fn checked_slice(&self, range: core::ops::Range<usize>) -> Option<Self> {
        self.get(range)
    }

    fn as_bytes(&self) -> &[u8] {
        self
    }
}

#[cfg(feature = "bytes")]
impl ViewBacking for bytes::Bytes {
    fn split_at(mut self, length: usize) -> Option<(Self, Self)> {
        (length <= self.len()).then(|| {
            let prefix = self.split_to(length);
            (prefix, self)
        })
    }

    fn checked_slice(&self, range: core::ops::Range<usize>) -> Option<Self> {
        (range.start <= range.end && range.end <= self.len()).then(|| self.slice(range))
    }

    fn as_bytes(&self) -> &[u8] {
        self
    }
}

/// Normalizes accepted generated view inputs into retained backing storage.
#[doc(hidden)]
pub trait ViewInput {
    /// The backing retained by the generated view.
    type Backing: ViewBacking;

    /// Converts this input without copying its bytes.
    fn into_view_backing(self) -> Self::Backing;
}

impl ViewInput for &[u8] {
    type Backing = Self;

    fn into_view_backing(self) -> Self::Backing {
        self
    }
}

impl<'wire, const N: usize> ViewInput for &'wire [u8; N] {
    type Backing = &'wire [u8];

    fn into_view_backing(self) -> Self::Backing {
        self
    }
}

#[cfg(feature = "bytes")]
impl ViewInput for bytes::Bytes {
    type Backing = Self;

    fn into_view_backing(self) -> Self::Backing {
        self
    }
}

/// Associates a semantic wire value with its generated read view.
#[doc(hidden)]
pub trait WireViewType {
    /// The typed failure returned while validating this representation.
    type DecodeError<'wire>: core::fmt::Debug + core::fmt::Display;

    /// The generated bytes-backed view for input with lifetime `'wire`.
    #[cfg(not(feature = "bytes"))]
    type View<'wire>: Copy + Clone;

    /// The generated bytes-backed view for owned input.
    #[cfg(feature = "bytes")]
    type View<'wire>: Clone;
}

/// A bytes-backed generated wire view.
#[doc(hidden)]
pub trait WireView<'wire>: Sized {
    /// The typed failure returned while validating the view.
    type DecodeError: core::fmt::Debug + core::fmt::Display;

    /// Validates one leading representation and creates its view.
    #[cfg(not(feature = "bytes"))]
    fn parse_view(input: &'wire [u8]) -> Result<(Self, &'wire [u8]), Self::DecodeError>;

    /// Validates one complete borrowed representation and creates its view.
    #[cfg(not(feature = "bytes"))]
    fn parse_complete(input: &'wire [u8]) -> Result<Self, Self::DecodeError> {
        let input_len = input.len();
        let (view, suffix) = Self::parse_view(input)?;
        if suffix.is_empty() {
            Ok(view)
        } else {
            Err(Self::trailing_bytes_error(view.as_bytes().len(), input_len))
        }
    }

    /// Validates one leading representation from owned input and creates its view.
    #[cfg(feature = "bytes")]
    fn parse_view(input: bytes::Bytes) -> Result<(Self, bytes::Bytes), Self::DecodeError>;

    /// Validates one complete owned representation and creates its view.
    #[cfg(feature = "bytes")]
    fn parse_complete(input: bytes::Bytes) -> Result<Self, Self::DecodeError> {
        let input_len = input.len();
        let (view, suffix) = Self::parse_view(input)?;
        if suffix.is_empty() {
            Ok(view)
        } else {
            Err(Self::trailing_bytes_error(view.as_bytes().len(), input_len))
        }
    }

    /// Builds this view's typed error for trailing input.
    fn trailing_bytes_error(represented: usize, input: usize) -> Self::DecodeError;

    /// Returns this view's exact represented bytes.
    #[cfg(not(feature = "bytes"))]
    fn as_bytes(&self) -> &'wire [u8];

    /// Returns this view's exact represented bytes.
    #[cfg(feature = "bytes")]
    fn as_bytes(&self) -> &[u8];
}

/// Generated semantic validation for a structurally decoded view.
#[doc(hidden)]
pub trait WireViewValidation<'wire> {
    /// The human-owned validation error.
    type ValidationError: core::fmt::Debug + core::fmt::Display;

    /// Validates decoded field and model invariants.
    fn validate(&self) -> Result<(), Self::ValidationError>;

    /// Frames and validates one complete borrowed representation.
    #[cfg(not(feature = "bytes"))]
    #[doc(hidden)]
    fn parse_validated_complete(input: &'wire [u8]) -> Result<Self, Self::ValidationError>
    where
        Self: Sized + WireView<'wire>,
        Self::ValidationError: From<<Self as WireView<'wire>>::DecodeError>,
    {
        let input_len = input.len();
        let (view, suffix) = Self::parse_view(input).map_err(Self::ValidationError::from)?;
        view.validate()?;
        if suffix.is_empty() {
            Ok(view)
        } else {
            Err(Self::ValidationError::from(Self::trailing_bytes_error(
                view.as_bytes().len(),
                input_len,
            )))
        }
    }

    /// Frames and validates one complete owned representation.
    #[cfg(feature = "bytes")]
    #[doc(hidden)]
    fn parse_validated_complete(input: bytes::Bytes) -> Result<Self, Self::ValidationError>
    where
        Self: Sized + WireView<'wire>,
        Self::ValidationError: From<<Self as WireView<'wire>>::DecodeError>,
    {
        let input_len = input.len();
        let (view, suffix) = Self::parse_view(input).map_err(Self::ValidationError::from)?;
        view.validate()?;
        if suffix.is_empty() {
            Ok(view)
        } else {
            Err(Self::ValidationError::from(Self::trailing_bytes_error(
                view.as_bytes().len(),
                input_len,
            )))
        }
    }
}

